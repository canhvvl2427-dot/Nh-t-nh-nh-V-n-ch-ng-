create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  title text not null,
  content text not null,
  published boolean not null default true,
  created_at timestamptz not null default now(),
  author_name text not null default 'Ẩn danh',
  category text not null default 'Văn mẫu'
);

alter table public.posts add column if not exists title text;
alter table public.posts add column if not exists content text;
alter table public.posts add column if not exists published boolean not null default true;
alter table public.posts add column if not exists created_at timestamptz not null default now();
alter table public.posts add column if not exists author_name text not null default 'Ẩn danh';
alter table public.posts add column if not exists category text not null default 'Văn mẫu';
alter table public.posts enable row level security;
grant select, insert on public.posts to anon, authenticated;
grant usage, select on sequence public.posts_id_seq to anon, authenticated;
drop policy if exists "Anyone can read posts" on public.posts;
create policy "Anyone can read posts" on public.posts for select to anon, authenticated using (true);
drop policy if exists "Anyone can submit posts" on public.posts;
create policy "Anyone can submit posts" on public.posts for insert to anon, authenticated with check (
  char_length(trim(title)) between 1 and 200
  and char_length(trim(author_name)) between 1 and 60
  and char_length(trim(content)) between 1 and 20000
  and category in ('Đọc hiểu','Ôn tập văn','Văn mẫu','Diễn đạt','Tác phẩm')
);
